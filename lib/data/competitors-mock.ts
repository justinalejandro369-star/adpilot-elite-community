// Helper functions

export function getCompetitorAds(clientSlug?: string): CompetitorAd[] {
  if (clientSlug) {
    return mockCompetitorAds.filter((ad) => ad.clientSlug === clientSlug);
  }
  return mockCompetitorAds;
}

export function getCompetitorInsights(clientSlug?: string): CompetitorInsight[] {
  if (clientSlug) {
    return mockCompetitorInsights.filter((i) => i.clientSlug === clientSlug);
  }
  return mockCompetitorInsights;
}

export function getFormatDistribution(): { format: string; count: number }[] {
  const counts: Record<string, number> = {};
  for (const ad of mockCompetitorAds) {
    counts[ad.creativeType] = (counts[ad.creativeType] || 0) + 1;
  }
  return Object.entries(counts)
    .map(([format, count]) => ({ format, count }))
    .sort((a, b) => b.count - a.count);
}
